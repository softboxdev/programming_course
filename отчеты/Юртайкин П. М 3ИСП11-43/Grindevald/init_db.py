import sqlite3

# ---------- 1. ПОДКЛЮЧЕНИЕ ----------
# Если файла app.db нет — он будет создан автоматически.
# Если есть — подключение произойдёт к существующему файлу.
conn = sqlite3.connect('app.db')

# ---------- 2. СОЗДАНИЕ КУРСОРА ----------
# Через курсор мы будем отправлять SQL-команды в базу.
cursor = conn.cursor()

# ---------- 3. ВЫПОЛНЕНИЕ DDL ----------
# Создаём таблицу tasks (задачи) с тремя колонками.
# IF NOT EXISTS — защита от ошибки, если таблица уже существует:
#   при повторном запуске скрипта ошибки не будет.
#
# Разбор колонок:
#   id     INTEGER PRIMARY KEY — целое число, уникальный идентификатор строки.
#                                SQLite автоматически заполняет его (1, 2, 3...).
#   title  TEXT NOT NULL       — текст, обязательное поле (нельзя оставить пустым).
#   status TEXT DEFAULT 'new'  — текст; если значение не передано,
#                                автоматически ставится 'new' (новая задача).
cursor.execute("""
    CREATE TABLE IF NOT EXISTS tasks (
        id     INTEGER PRIMARY KEY,
        title  TEXT NOT NULL,
        status TEXT DEFAULT 'new'
    )
""")

# ---------- 4. ФИКСАЦИЯ (COMMIT) ----------
# КРИТИЧЕСКИ ВАЖНЫЙ ШАГ.
# Без commit() структура таблицы останется только в памяти
# и НЕ будет записана в файл app.db.
# Если закрыть соединение без commit — таблица исчезнет.
conn.commit()

# ---------- 5. ЗАКРЫТИЕ СОЕДИНЕНИЯ ----------
# Освобождает файл базы данных.
# Если не закрыть — файл может остаться заблокированным
# для других программ (например, для DB Browser for SQLite).
conn.close()

print("База данных и таблица tasks успешно созданы.")